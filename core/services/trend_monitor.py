    def _init_reddit(self):
        """Initialize Reddit client (PRAW) if credentials available"""
        try:
            import praw
            
            client_id = os.getenv("REDDIT_CLIENT_ID")
            client_secret = os.getenv("REDDIT_CLIENT_SECRET")
            user_agent = os.getenv("REDDIT_USER_AGENT", "MAK AI TrendJack v1.0")
            
            if client_id and client_secret:
                reddit = praw.Reddit(
                    client_id=client_id,
                    client_secret=client_secret,
                    user_agent=user_agent
                )
                log.info("✅ Reddit API connected")
                return reddit
            else:
                log.warning("⚠️ Reddit credentials not found, using mock data")
                return None
        except ImportError:
            log.warning("⚠️ PRAW not installed, using mock data")
            return None
    
    async def get_trending_topics(
        self,
        niche: ContentNiche = ContentNiche.TECHNOLOGY,
        limit: int = 10
    ) -> List[TrendingTopic]:
        """
        Fetch trending topics from multiple free sources.
        
        Sources:
        - Reddit (free, rate limit: 60 req/min)
        - HackerNews (free, unlimited)
        - Google Trends (free via pytrends)
        """
        all_trends = []
        
        # 1. Reddit Hot Posts
        reddit_trends = await self._get_reddit_trends(niche, limit)
        all_trends.extend(reddit_trends)
        
        # 2. HackerNews Top Stories
        hn_trends = await self._get_hackernews_trends(limit)
        all_trends.extend(hn_trends)
        
        # 3. Google Trends (if pytrends installed)
        google_trends = await self._get_google_trends(limit)
        all_trends.extend(google_trends)
        
        # Score all trends for video potential
        scored_trends = await self._score_trends(all_trends)
        
        # Sort by score and return top results
        scored_trends.sort(key=lambda x: x.score, reverse=True)
        
        log.info(f"🔥 Found {len(scored_trends)} trending topics")
        
        return scored_trends[:limit]
    
    async def _get_reddit_trends(
        self,
        niche: ContentNiche,
        limit: int
    ) -> List[TrendingTopic]:
        """Fetch hot posts from niche-specific subreddits"""
        trends = []
        subreddits = self.NICHE_SUBREDDITS.get(niche, ["all"])
        
        if self.reddit_client:
            try:
                for subreddit_name in subreddits[:2]:  # Limit to 2 subs
                    subreddit = self.reddit_client.subreddit(subreddit_name)
                    
                    for post in subreddit.hot(limit=5):
                        trends.append(TrendingTopic(
                            title=post.title,
                            source=f"reddit/r/{subreddit_name}",
                            score=0,  # Will be scored later
                            url=f"https://reddit.com{post.permalink}",
                            engagement=post.score,
                            timestamp=datetime.utcnow().isoformat()
                        ))
            except Exception as e:
                log.error(f"Reddit API error: {e}")
        else:
            # Mock data for development
            trends = self._get_mock_reddit_trends(niche)
        
        return trends
    
    async def _get_hackernews_trends(self, limit: int) -> List[TrendingTopic]:
        """Fetch top stories from HackerNews (free, unlimited)"""
        try:
            import httpx
            
            async with httpx.AsyncClient() as client:
                # Get top story IDs
                response = await client.get(
                    "https://hacker-news.firebaseio.com/v0/topstories.json"
                )
                story_ids = response.json()[:limit]
                
                trends = []
                for story_id in story_ids[:5]:  # Limit API calls
                    story_response = await client.get(
                        f"https://hacker-news.firebaseio.com/v0/item/{story_id}.json"
                    )
                    story = story_response.json()
                    
                    if story and story.get("title"):
                        trends.append(TrendingTopic(
                            title=story["title"],
                            source="hackernews",
                            score=0,
                            url=story.get("url", ""),
                            engagement=story.get("score", 0),
                            timestamp=datetime.utcnow().isoformat()
                        ))
                
                return trends
        except Exception as e:
            log.warning(f"HackerNews API error: {e}")
            return []
    
    async def _get_google_trends(self, limit: int) -> List[TrendingTopic]:
        """Fetch Google Trends data (free via pytrends)"""
        try:
            from pytrends.request import TrendReq
            
            pytrends = TrendReq(hl='en-US', tz=360)
            trending = pytrends.trending_searches(pn='united_states')
            
            trends = []
            for i, row in trending.head(limit).iterrows():
                trends.append(TrendingTopic(
                    title=row[0],
                    source="google_trends",
                    score=0,
                    timestamp=datetime.utcnow().isoformat()
                ))
            
            return trends
        except Exception as e:
            log.warning(f"Google Trends error: {e}")
            return []
    
