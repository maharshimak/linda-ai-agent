    async def _score_trends(self, trends: List[TrendingTopic]) -> List[TrendingTopic]:
        """
        AI scores each trend for video potential (0-100).
        
        Scoring factors:
        - Viral keywords presence (+20)
        - Engagement level (+30)
        - Question/curiosity format (+15)
        - Novelty indicators (+15)
        - Visual potential (+20)
        """
        for trend in trends:
            score = 0
            title_lower = trend.title.lower()
            
            # 1. Viral keywords (+20 max)
            keyword_matches = sum(
                1 for kw in self.VIDEO_POTENTIAL_KEYWORDS 
                if kw in title_lower
            )
            score += min(keyword_matches * 5, 20)
            
            # 2. Engagement level (+30 max)
            if trend.engagement > 10000:
                score += 30
            elif trend.engagement > 5000:
                score += 20
            elif trend.engagement > 1000:
                score += 10
            
            # 3. Question/Curiosity format (+15)
            if "?" in trend.title or any(w in title_lower for w in ["why", "how", "what"]):
                score += 15
            
            # 4. Novelty indicators (+15)
            if any(w in title_lower for w in ["just", "new", "first", "breaking", "revealed"]):
                score += 15
            
            # 5. Visual potential (+20)
            visual_keywords = ["video", "shows", "watch", "see", "incredible", "amazing"]
            if any(w in title_lower for w in visual_keywords):
                score += 20
            
            # Normalize to 0-100
            trend.score = min(score, 100)
            
            # Generate suggested angle
            trend.suggested_angle = self._suggest_angle(trend)
        
        return trends
    
    def _suggest_angle(self, trend: TrendingTopic) -> str:
        """Suggest the best video angle for a trend"""
        title_lower = trend.title.lower()
        
        if "?" in trend.title:
            return "Answer the question with surprising facts"
        elif "how" in title_lower:
            return "Step-by-step explainer with visual demonstrations"
        elif "why" in title_lower:
            return "Deep dive into the hidden reasons"
        elif any(w in title_lower for w in ["breaking", "just", "new"]):
            return "Breaking news style with urgency"
        elif any(w in title_lower for w in ["secret", "hidden", "revealed"]):
            return "Exposé style revealing the truth"
        else:
            return "Documentary-style educational content"
    
    async def auto_generate_daily_videos(
        self,
        user_id: str,
        niche: ContentNiche,
        video_count: int = 5
    ) -> List[AutoGeneratedVideo]:
        """
        The Obsession Engine: Auto-generate videos overnight.
        
        This runs as a cron job at midnight:
        1. Fetch trending topics for user's niche
        2. Generate videos for top trends
        3. User wakes up to ready content
        
        Args:
            user_id: The user to generate for
            niche: User's content niche
            video_count: Number of videos (1=free, 5=pro, 50=agency)
        """
        log.info(f"🌙 Auto-generating {video_count} videos for user {user_id}")
        
        # 1. Get trending topics
        trends = await self.get_trending_topics(niche, limit=video_count)
        
        # 2. Generate video for each trend
        generated_videos = []
        
        for trend in trends:
            auto_video = AutoGeneratedVideo(
                trend=trend,
                status="generating"
            )
            
            try:
                # Generate script from trend
                script = await self._generate_script_from_trend(trend)
                auto_video.script = script
                
                # Generate video (uses existing pipeline)
                video_path = await self._generate_video(
                    topic=trend.title,
                    script=script,
                    style="cinematic"
                )
                
                auto_video.video_path = video_path
                auto_video.status = "ready"
                auto_video.generated_at = datetime.utcnow().isoformat()
                
                log.info(f"✅ Generated video for trend: {trend.title[:50]}...")
                
            except Exception as e:
                log.error(f"❌ Failed to generate video: {e}")
                auto_video.status = "failed"
            
            generated_videos.append(auto_video)
        
        log.info(f"🎬 Completed: {len([v for v in generated_videos if v.status == 'ready'])}/{len(generated_videos)} videos")
        
        return generated_videos
    
    async def _generate_script_from_trend(self, trend: TrendingTopic) -> str:
        """Generate a viral script from a trending topic"""
        # Use existing script generation or AI
        try:
            from core.ai.model_router import smart_complete
            
            prompt = f"""
            Create a 45-second viral video script about this trending topic:
            "{trend.title}"
            
            Angle: {trend.suggested_angle}
            Source: {trend.source}
            
            Requirements:
            - Hook in first 3 seconds (shocking/curious)
            - 5-6 scenes total
            - Each scene is one sentence
            - End with call-to-action or thought-provoking question
            - Make it feel urgent and timely
            
            Return ONLY the script, nothing else.
            """
            
            script = await smart_complete(
                task="script_writing",
                prompt=prompt,
                max_cost=0.05
            )
            
            return script
        except Exception as e:
            log.warning(f"Script generation fallback: {e}")
            # Fallback script template
            return f"""
            {trend.title}
            
            Here's what you need to know.
            
            This is why everyone's talking about it.
            
            The implications are massive.
            
            What do you think? Comment below.
            """
    
    async def _generate_video(
        self,
        topic: str,
        script: str,
        style: str = "cinematic"
    ) -> str:
        """Generate video using existing pipeline"""
        try:
            from video_engine.engine import VideoEngine
            
            engine = VideoEngine()
            video_path = engine.generate_video(
                topic=f"{topic}\n\n{script}",
                language="English",
                duration="45s"
            )
            
            return str(video_path)
        except Exception as e:
            log.error(f"Video generation error: {e}")
            raise
    
