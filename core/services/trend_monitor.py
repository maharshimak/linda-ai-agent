class ContentNiche(Enum):
    """User content niches for personalized trends"""
    TECHNOLOGY = "technology"
    BUSINESS = "business"
    ENTERTAINMENT = "entertainment"
    EDUCATION = "education"
    LIFESTYLE = "lifestyle"
    NEWS = "news"
    SCIENCE = "science"
    GAMING = "gaming"
    FITNESS = "fitness"
    FINANCE = "finance"


@dataclass
class TrendingTopic:
    """A trending topic with viral potential score"""
    title: str
    source: str
    score: float  # 0-100 viral potential
    url: Optional[str] = None
    suggested_angle: str = ""
    keywords: List[str] = field(default_factory=list)
    timestamp: str = ""
    engagement: int = 0  # upvotes, shares, etc.


@dataclass
class AutoGeneratedVideo:
    """Pre-generated video ready for user"""
    trend: TrendingTopic
    video_path: Optional[str] = None
    thumbnail_path: Optional[str] = None
    script: str = ""
    status: str = "pending"  # pending, generating, ready, failed
    generated_at: Optional[str] = None


